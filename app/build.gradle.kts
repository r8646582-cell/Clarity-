    // Release signing comes from environment variables (GitHub secrets in CI), never from the repo.
    // Without them, release builds fall back to the debug key so the APK still installs.
    val releaseKeystore = System.getenv("PURPOSE_KEYSTORE_PATH")?.let(::file)?.takeIf { it.exists() }
    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = releaseKeystore
                storePassword = System.getenv("PURPOSE_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("PURPOSE_KEY_ALIAS")
                keyPassword = System.getenv("PURPOSE_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
